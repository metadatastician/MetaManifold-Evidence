# Generate rocq/ExplorerTable.v from residual-evidence-types'
# tests/correspondence/ExplorerTable.agda (the 546-row table the Agda finite
# checker is proved equal to), so the Rocq port of the checker can be compared
# with it row for row (rocq/Correspondence.v).  The table is not retyped: each
# row is transcribed token by token (∷ to ::, [] to nil, no-candidate to
# no_candidate) after every token has been checked against a closed list.
#
# Usage: scripts/gen-rocq-explorer-table.sh [OUTPUT]  (default rocq/ExplorerTable.v)
# RET_ROOT overrides the residual-evidence-types checkout
# (default _build/dependencies/residual-evidence-types, see fetch-layer-a.sh).
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
export LC_ALL=C

ret_root="${RET_ROOT:-_build/dependencies/residual-evidence-types}"
src="$ret_root/tests/correspondence/ExplorerTable.agda"
out="${1:-rocq/ExplorerTable.v}"
test -f "$src" || { echo "ERROR: $src not found (run scripts/fetch-layer-a.sh)" >&2; exit 1; }

digest="$(sha256sum "$src" | cut -d' ' -f1)"
tmp="$(mktemp "${out}.XXXXXX")"
trap 'rm -f -- "$tmp"' EXIT

awk -v digest="$digest" -v srcname="tests/correspondence/ExplorerTable.agda" '
function fail(msg) { printf "ERROR: %s:%d: %s\n", srcname, NR, msg > "/dev/stderr"; bad = 1; exit 1 }
function emit(body,   i, n, t, toks, outl) {
  n = split(body, toks, " ")
  if (toks[1] != "row") fail("row expected: " body)
  outl = ""
  for (i = 1; i <= n; i++) {
    t = toks[i]
    if (t == "\342\210\267") t = "::"
    else {
      gsub(/\[\]/, "nil", t)
      gsub(/no-candidate/, "no_candidate", t)
      if (t !~ /^\(*(row|negsuc|pos|[0-9]+|exact|sign|magnitude|true|false|entailed|refuted|unresolved|inconsistent|identified|unidentified|no_candidate|nil)\)*$/)
        fail("unrecognised token: " toks[i])
    }
    outl = outl (i > 1 ? " " : "") t
  }
  printf "  %s ::\n", outl
  rows++
}
BEGIN {
  state = 0; rows = 0
  print "(* SPDX-License-Identifier: MPL-2.0 *)"
  print "(* SPDX-FileCopyrightText: 2026 Jonathan D.A. Jewell *)"
  print ""
  print "(* GENERATED by scripts/gen-rocq-explorer-table.sh from residual-evidence-types"
  print "   " srcname
  print "   (sha256 " digest "),"
  print "   which that repository generates from residual-evidence-explorer.html"
  print "   (model signed-integer-v1).  Do not edit. *)"
  print ""
  print "From MetaManifoldEvidence Require Import ResidualEvidence."
  print "Import FiniteInt Row Checker."
  print ""
  print "Definition expected : list Checker.Row :="
}
state == 0 && $0 == "expected : List Row" { state = 1; next }
state == 1 { if ($0 == "expected =") { state = 2; next } else fail("expected \"expected =\"") }
state == 2 {
  if (rows == 0) {
    if (substr($0, 1, 8) != "    row ") fail("first row expected: " $0)
    emit(substr($0, 5)); next
  }
  if ($0 == "  \342\210\267 []") { state = 3; next }
  if (substr($0, 1, 10) != "  \342\210\267 row ") fail("row expected: " $0)
  emit(substr($0, 6)); next
}
state == 3 && NF > 0 { fail("text after the table terminator: " $0) }
END {
  if (bad) exit 1
  if (state != 3) { printf "ERROR: %s: table not found or not terminated\n", srcname > "/dev/stderr"; exit 1 }
  if (rows != 546) { printf "ERROR: %s: %d rows, expected 546\n", srcname, rows > "/dev/stderr"; exit 1 }
  print "  nil."
}
' "$src" > "$tmp"

mv -- "$tmp" "$out"
trap - EXIT
echo "wrote $out (546 rows from $src)"
