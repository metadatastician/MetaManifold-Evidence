# Generate lean/CountsJuliaTable.lean from the Agda table
# agda/src/MetaManifold/Evidence/CountsJuliaTable.agda, so the 169-row
# `expected` list is never retyped by hand. Strict: any line of the Agda
# `expected` block that is not a row, the list end, or the declaration is an
# error, as is an empty table.
#
# Usage: scripts/gen-lean-table.sh [OUTPUT]   (default lean/CountsJuliaTable.lean)
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
src=agda/src/MetaManifold/Evidence/CountsJuliaTable.agda
out="${1:-lean/CountsJuliaTable.lean}"
test -f "$src" || { echo "ERROR: $src not found" >&2; exit 1; }

tmp="$(mktemp)"
trap 'rm -f -- "$tmp" "$tmp.rows"' EXIT

LC_ALL=C.UTF-8 awk -v src="$src" '
BEGIN {
  state = 0; rows = 0
  print "-- SPDX-License-Identifier: AGPL-3.0-or-later"
  print "-- SPDX-FileCopyrightText: 2026 Jonathan D.A. Jewell"
  print "--"
  print "-- GENERATED by scripts/gen-lean-table.sh from " src ","
  print "-- itself generated by julia/gen/emit_table.jl from"
  print "-- MetaManifoldEvidence.count_verdict and fibre over reads, noise in 0..12."
  print "-- Do not edit."
  print ""
  print "import CountsGrid"
  print ""
  print "namespace MetaManifoldEvidence.CountsJuliaTable"
  print ""
  print "open MetaManifoldEvidence.ResidualEvidence (Verdict)"
  print "open MetaManifoldEvidence.CountsGrid (Row)"
  print ""
  print "def expected : List Row :="
}
function fail(msg) { printf "ERROR: %s:%d: %s\n", src, NR, msg > "/dev/stderr"; bad = 1; exit 1 }
state == 0 && /^expected : List Row$/ { state = 1; next }
state == 1 { if ($0 == "expected =") { state = 2; next } else fail("expected `expected =`") }
state == 2 {
  if ($0 == "  []") { state = 3; print "  []"; next }
  if ($0 ~ /^  row [0-9]+ [0-9]+ (entailed|refuted|unresolved|inconsistent) [0-9]+ [0-9]+ ∷$/) {
    printf "  Row.row %s %s Verdict.%s %s %s ::\n", $2, $3, $4, $5, $6
    rows++
    next
  }
  fail("unrecognised table line: " $0)
}
state == 3 && NF > 0 { fail("content after the end of the table: " $0) }
END {
  if (bad) exit 1
  if (state != 3) { printf "ERROR: %s: table not found or not terminated\n", src > "/dev/stderr"; exit 1 }
  if (rows == 0) { printf "ERROR: %s: empty table\n", src > "/dev/stderr"; exit 1 }
  print ""
  print "end MetaManifoldEvidence.CountsJuliaTable"
  printf "%d\n", rows > "/dev/stderr"
}
' "$src" >"$tmp" 2>"$tmp.rows" || { cat "$tmp.rows" >&2; rm -f -- "$tmp.rows"; exit 1; }
rows="$(cat "$tmp.rows")"; rm -f -- "$tmp.rows"
mv -- "$tmp" "$out"
trap - EXIT
echo "gen-lean-table: $rows rows -> $out"
