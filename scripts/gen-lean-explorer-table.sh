# Generate lean/ExplorerTable.lean from residual-evidence-types'
# tests/correspondence/ExplorerTable.agda (the 546-row table its Agda checker
# is proved equal to), so the table is never retyped by hand. Strict: every
# line of the Agda `expected` block must be a row in the exact generated
# shape, the list end, or the declaration; anything else is an error.
#
# Usage: scripts/gen-lean-explorer-table.sh [OUTPUT]   (default lean/ExplorerTable.lean)
# RET_ROOT overrides the residual-evidence-types checkout
# (default _build/dependencies/residual-evidence-types, from fetch-layer-a.sh).
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
ret_root="${RET_ROOT:-_build/dependencies/residual-evidence-types}"
src="$ret_root/tests/correspondence/ExplorerTable.agda"
out="${1:-lean/ExplorerTable.lean}"
test -f "$src" || { echo "ERROR: $src not found (run scripts/fetch-layer-a.sh)" >&2; exit 1; }
rev="$(git -C "$ret_root" rev-parse HEAD 2>/dev/null || echo unknown)"

tmp="$(mktemp)"
trap 'rm -f -- "$tmp" "$tmp.rows"' EXIT

int='\((pos|negsuc) [0-9]+\)'
elem='(pos|negsuc) [0-9]+'
row_re="^row $int [0-9]+ (exact|sign|magnitude) (true|false) [0-9]+ (entailed|refuted|unresolved|inconsistent) (identified|unidentified|no-candidate) (\[\]|\($elem( ∷ $elem)* ∷ \[\]\))\$"

ROW_RE="$row_re" LC_ALL=C.UTF-8 awk -v src="$src" -v rev="$rev" '
BEGIN {
  state = 0; rows = 0; row_re = ENVIRON["ROW_RE"]
  print "-- SPDX-License-Identifier: MPL-2.0"
  print "-- SPDX-FileCopyrightText: 2026 Jonathan D.A. Jewell"
  print "--"
  print "-- GENERATED by scripts/gen-lean-explorer-table.sh from residual-evidence-types"
  print "-- tests/correspondence/ExplorerTable.agda at " rev ","
  print "-- itself generated by tests/correspondence/generate-table.js from"
  print "-- residual-evidence-explorer.html (model signed-integer-v1). Do not edit."
  print ""
  print "import ResidualEvidence"
  print ""
  print "namespace MetaManifoldEvidence.ExplorerTable"
  print ""
  print "open MetaManifoldEvidence.ResidualEvidence"
  print ""
  print "def expected : List Row :="
}
function fail(msg) { printf "ERROR: %s:%d: %s\n", src, NR, msg > "/dev/stderr"; bad = 1; exit 1 }
function lint(tok, n) { return (tok == "pos" ? "Int.pos " : "Int.negsuc ") n }
function emit(body,    f, n, i, vals, res) {
  if (body !~ row_re) fail("unrecognised row: " body)
  n = split(body, f, " ")
  # f[1]=row f[2]=(pos|(negsuc f[3]=K) f[4]=bound f[5]=view f[6]=flag
  # f[7]=count f[8]=presence f[9]=identity f[10..n]=values
  res = lint(substr(f[2], 2), substr(f[3], 1, length(f[3]) - 1))
  if (f[10] == "[]") {
    if (n != 10) fail("trailing tokens after []")
    vals = "[]"
  } else {
    vals = ""
    # (pos 1 ∷ negsuc 2 ∷ []) -> pairs at 10,11 / 13,14 / ...
    for (i = 10; i < n; i += 3) {
      t = f[i]; if (i == 10) t = substr(t, 2)
      vals = vals (vals == "" ? "" : ", ") lint(t, f[i + 1])
      if (f[i + 2] != "∷") fail("malformed value list")
    }
    if (f[n] != "[])") fail("malformed value list end")
    vals = "[" vals "]"
  }
  out[++rows] = sprintf("Row.row (%s) %s View.%s %s %s Verdict.%s IdStatus.«%s» %s", \
    res, f[4], f[5], f[6], f[7], f[8], f[9], vals)
}
state == 0 && /^expected : List Row$/ { state = 1; next }
state == 1 { if ($0 == "expected =") { state = 2; next } else fail("expected `expected =`") }
state == 2 {
  line = $0
  if (rows == 0 && sub(/^    /, "", line)) { emit(line); next }
  if ($0 == "  ∷ []") { state = 3; next }
  if (rows > 0 && sub(/^  ∷ /, "", line)) { emit(line); next }
  fail("unrecognised table line: " $0)
}
state == 3 && NF > 0 { fail("content after the end of the table: " $0) }
END {
  if (bad) exit 1
  if (state != 3) { printf "ERROR: %s: table not found or not terminated\n", src > "/dev/stderr"; exit 1 }
  if (rows == 0) { printf "ERROR: %s: empty table\n", src > "/dev/stderr"; exit 1 }
  # A list literal: Lean elaborates it without the deep recursion a
  # 546-deep `::` chain needs.
  print "  ["
  for (i = 1; i <= rows; i++) printf "    %s%s\n", out[i], (i < rows ? "," : "")
  print "  ]"
  print ""
  print "end MetaManifoldEvidence.ExplorerTable"
  printf "%d\n", rows > "/dev/stderr"
}
' "$src" >"$tmp" 2>"$tmp.rows" || { cat "$tmp.rows" >&2; exit 1; }
rows="$(cat "$tmp.rows")"
mv -- "$tmp" "$out"
echo "gen-lean-explorer-table: $rows rows -> $out"
